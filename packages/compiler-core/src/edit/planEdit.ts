import type { ParamDefinition } from "../registry/ParamDefinition.js";
import { NAMED_COLORS } from "../registry/colors.config.js";
import { GROUP_DEFINITION, SHAPE_DEFINITIONS } from "../registry/shapes.config.js";
import type { ParamValue, ResolvedGroup, ResolvedShape, Scene, SourceOrigin } from "../semantic/Scene.js";
import type { Span } from "../ast/Span.js";
import { groupChain } from "../semantic/groupTransform.js";

/**
 * Turns a visual change ("this circle now has x=120") into the smallest edit
 * of the source text. It never regenerates the file: it rewrites the exact
 * range where the value is written, or inserts `name=value` for a parameter
 * that was left at its default, and leaves everything else (comments,
 * formatting, other statements) byte for byte as it was.
 *
 * It refuses, with a reason the UI can explain, whenever applying the change
 * would be a guess: a value computed by an expression (`x=cx + 10`), or a
 * shape generated by a loop/function (editing the one literal would silently
 * move every instance).
 */
export interface TextChange {
  /** Offsets into the original text, `[start, end)`. `start === end` is a pure insertion. */
  readonly start: number;
  readonly end: number;
  readonly text: string;
}

export type EditRequest =
  | {
      readonly kind: "setParams";
      /** A shape id or a group id from the Scene. */
      readonly targetId: string;
      readonly params: Readonly<Record<string, ParamValue>>;
      /** The user confirmed that a loop/function-generated shape should change for every instance. */
      readonly allowShared?: boolean;
    }
  | { readonly kind: "delete"; readonly targetId: string; readonly allowShared?: boolean };

export type EditRefusal =
  | "unknown-target"
  | "no-source"
  | "shared"
  | "expression"
  | "invalid-value"
  | "unknown-param";

export type EditPlan =
  | { readonly ok: true; readonly changes: readonly TextChange[]; readonly summary: string }
  | {
      readonly ok: false;
      readonly reason: EditRefusal;
      readonly message: string;
      /** For `expression`: the variables the value is computed from. */
      readonly dependsOn?: readonly string[];
      /** For `expression` / `shared`: where to look in the source instead. */
      readonly span?: Span;
      readonly instances?: number;
    };

const refuse = (reason: EditRefusal, message: string, extra: Omit<Extract<EditPlan, { ok: false }>, "ok" | "reason" | "message"> = {}): EditPlan => ({
  ok: false,
  reason,
  message,
  ...extra,
});

const DEFINITIONS = new Map([...SHAPE_DEFINITIONS, GROUP_DEFINITION].map((definition) => [definition.name, definition]));
const MAX_MAGNITUDE = 1_000_000;

/** `120`, `3.5`, never `1e-7` (the lexer has no exponents) nor `-0`; at most 2 decimals. */
export function formatNumber(value: number): string {
  const rounded = Math.round(value * 100) / 100;
  return Object.is(rounded, -0) ? "0" : String(rounded);
}

const colorNameFor = (hex: string): string | undefined =>
  Object.entries(NAMED_COLORS).find(([, candidate]) => candidate.toLowerCase() === hex.toLowerCase())?.[0];

/** The source text for `value` as the language writes it, or an error message when it isn't valid for `param`. */
function literalFor(param: ParamDefinition, value: ParamValue): { text: string } | { error: string } {
  switch (param.type) {
    case "number": {
      if (typeof value !== "number" || !Number.isFinite(value) || Math.abs(value) > MAX_MAGNITUDE) {
        return { error: `'${param.name}' necesita un número entre -${MAX_MAGNITUDE} y ${MAX_MAGNITUDE}.` };
      }
      if (param.name === "opacidad" && (value < 0 || value > 1)) return { error: "La opacidad va de 0 a 1." };
      if ((param.name === "radio" || param.name === "ancho" || param.name === "alto" || param.name === "tamano") && value < 0) {
        return { error: `'${param.name}' no puede ser negativo.` };
      }
      return { text: formatNumber(value) };
    }
    case "color": {
      if (typeof value !== "string") return { error: `'${param.name}' necesita un color.` };
      if (Object.hasOwn(NAMED_COLORS, value)) return { text: value };
      if (!/^#[0-9a-fA-F]{3,8}$/.test(value)) return { error: `'${value}' no es un color válido (usa #rrggbb o un nombre).` };
      return { text: colorNameFor(value) ?? value.toLowerCase() };
    }
    case "string": {
      if (typeof value !== "string" || /["\n\r]/.test(value)) return { error: `'${param.name}' no puede contener comillas ni saltos de línea.` };
      if (param.allowedValues && !param.allowedValues.includes(value)) return { error: `Valores válidos para '${param.name}': ${param.allowedValues.join(", ")}.` };
      return { text: param.allowedValues ? value : `"${value}"` };
    }
    default:
      return { error: `'${param.name}' no se puede editar visualmente.` };
  }
}

type Target = { readonly kind: "shape"; readonly shape: ResolvedShape } | { readonly kind: "group"; readonly group: ResolvedGroup };

function findTarget(scene: Scene, id: string): Target | undefined {
  const shape = scene.shapes.find((candidate) => candidate.id === id);
  if (shape) return { kind: "shape", shape };
  const group = scene.groups?.find((candidate) => candidate.id === id);
  return group ? { kind: "group", group } : undefined;
}

export function planEdit(source: string, scene: Scene, request: EditRequest): EditPlan {
  const target = findTarget(scene, request.targetId);
  if (!target) return refuse("unknown-target", `No existe '${request.targetId}' en la escena actual.`);
  const origin = target.kind === "shape" ? target.shape.origin : target.group.origin;
  if (!origin) return refuse("no-source", "Esta figura no tiene un origen en el código.");

  if (origin.dynamic && !request.allowShared) {
    return refuse(
      "shared",
      `La genera un bucle o una función (${origin.instances} veces): cambiarla aquí afectaría a todas. Edita el código, o confirma el cambio para todas.`,
      { span: origin.callSpan, instances: origin.instances },
    );
  }

  return request.kind === "delete" ? planDelete(source, scene, target, origin, request) : planSetParams(target, origin, request);
}

function planSetParams(target: Target, origin: SourceOrigin, request: Extract<EditRequest, { kind: "setParams" }>): EditPlan {
  const kind = target.kind === "shape" ? target.shape.kind : "grupo";
  const definition = DEFINITIONS.get(kind);
  const current = target.kind === "shape" ? target.shape.params : target.group.params;
  if (!definition) return refuse("unknown-target", `No se puede editar una figura de tipo '${kind}'.`);

  const changes: TextChange[] = [];
  const appended: string[] = [];
  const written: string[] = [];

  for (const [name, value] of Object.entries(request.params)) {
    const param = definition.params.find((candidate) => candidate.name === name);
    const paramOrigin = origin.params[name];
    if (!param || !paramOrigin) return refuse("unknown-param", `'${kind}' no tiene un parámetro '${name}'.`);

    const literal = literalFor(param, value);
    if ("error" in literal) return refuse("invalid-value", literal.error);
    if (current[name] === value) continue;

    switch (paramOrigin.editability) {
      case "literal":
        changes.push({ start: paramOrigin.span!.start, end: paramOrigin.span!.end, text: literal.text });
        break;
      case "default":
        appended.push(`${name}=${literal.text}`);
        break;
      case "expression":
        return refuse(
          "expression",
          `'${name}' se calcula con una expresión${paramOrigin.dependsOn?.length ? ` (usa ${paramOrigin.dependsOn.join(", ")})` : ""}; no la reemplazo por un número. Edítala en el código.`,
          { dependsOn: paramOrigin.dependsOn ?? [], ...(paramOrigin.span ? { span: paramOrigin.span } : {}) },
        );
    }
    written.push(`${name}=${literal.text}`);
  }

  if (appended.length > 0) {
    changes.push({ start: origin.appendAt, end: origin.appendAt, text: `${origin.hasArgs ? ", " : ""}${appended.join(", ")}` });
  }
  if (changes.length === 0) return { ok: true, changes: [], summary: "Sin cambios." };

  return { ok: true, changes: normalize(changes), summary: `${request.targetId}: ${written.join(", ")}` };
}

function planDelete(source: string, scene: Scene, target: Target, origin: SourceOrigin, request: EditRequest): EditPlan {
  // What disappears with the target: a group takes its whole subtree, and any connection that touches a vanished shape.
  const groups = new Map((scene.groups ?? []).map((group) => [group.id, group]));
  const removedShapes = new Set<string>();
  if (target.kind === "shape") {
    removedShapes.add(target.shape.id);
  } else {
    for (const shape of scene.shapes) {
      if (groupChain(shape.groupId, groups).some((group) => group.id === target.group.id)) removedShapes.add(shape.id);
    }
  }

  const spans: Span[] = [origin.statementSpan];
  const seen = new Set<number>([origin.site]);
  for (const connection of scene.connections) {
    if (!removedShapes.has(connection.fromId) && !removedShapes.has(connection.toId)) continue;
    const connectionOrigin = connection.origin;
    if (!connectionOrigin) continue;
    if (connectionOrigin.dynamic && !request.allowShared) {
      return refuse("shared", "Una conexión generada por un bucle usa esta figura; edita el código.", { span: connectionOrigin.callSpan });
    }
    if (!seen.has(connectionOrigin.site)) {
      seen.add(connectionOrigin.site);
      spans.push(connectionOrigin.statementSpan);
    }
  }

  // Drop spans that sit inside another deleted span (a connection written inside the group being deleted).
  const outer = spans.filter(
    (span, index) =>
      !spans.some(
        (other, otherIndex) =>
          otherIndex !== index &&
          other.start <= span.start &&
          other.end >= span.end &&
          // exact duplicates: keep only the first
          !(other.start === span.start && other.end === span.end && otherIndex > index),
      ),
  );
  const changes = outer.map((span) => deletion(source, span));
  const what = target.kind === "shape" ? "figura" : "grupo";
  return { ok: true, changes: normalize(changes), summary: `Eliminó ${what} ${request.targetId}` };
}

/** The statement, its ';', and — when nothing else is on the line — the whole line. */
function deletion(source: string, span: Span): TextChange {
  let end = span.end;
  let probe = end;
  while (source[probe] === " " || source[probe] === "\t") probe += 1;
  if (source[probe] === ";") end = probe + 1;

  const lineStart = source.lastIndexOf("\n", span.start - 1) + 1;
  const newline = source.indexOf("\n", end);
  const lineEnd = newline === -1 ? source.length : newline;
  const before = source.slice(lineStart, span.start);
  const after = source.slice(end, lineEnd);
  if (before.trim() === "" && after.trim() === "") {
    return { start: lineStart, end: newline === -1 ? lineEnd : lineEnd + 1, text: "" };
  }
  return { start: span.start, end, text: "" };
}

/** Sorted by position, with an insertion that touches the end of a replacement folded into it. */
function normalize(changes: readonly TextChange[]): TextChange[] {
  const sorted = [...changes].sort((a, b) => a.start - b.start || a.end - b.end);
  const merged: TextChange[] = [];
  for (const change of sorted) {
    const previous = merged.at(-1);
    if (previous && change.start === change.end && change.start === previous.end) {
      merged[merged.length - 1] = { ...previous, text: previous.text + change.text };
    } else {
      merged.push(change);
    }
  }
  return merged;
}

/** Applies changes (offsets into `source`) and returns the new text. Used by tests and by non-Monaco callers. */
export function applyChanges(source: string, changes: readonly TextChange[]): string {
  let result = source;
  for (const change of [...changes].sort((a, b) => b.start - a.start)) {
    result = result.slice(0, change.start) + change.text + result.slice(change.end);
  }
  return result;
}
